# Variable = A container of values to store different tpyes of data
# Such as integer, float, string, boolean, list, tuple, set, dictionary


#Strings is a series of character they can include numbers and symbols but are treated as character inside the quotation of the string.
#Assigning variables for a Strings 

First_name = "Gino"
food ="Pizza"
email ="gino@example.com"

print(f"My name is {First_name}")
print (f"I like {food}")
print(f"My email addresss is {email}")

#Integer is a whole number that can be positive, negative or zero. They do not have decimal points.
#Assigning variables for anInteger 

age = 23
quantity = 3
tot_students = 60

print(f"You are {age} years old")
print(f"The quantity of the soap products bought is {quantity}")
print(f"The total strength of the students in a class is {tot_students}")


#Float is a floating point number with a decimal portion.
#Assigning variables for a Float

price = 19.99
GPA = 3.5
distance = 2.5

print(f"The price of the item is ${price}")
print(f"Your GPA is {GPA}")
print(f"The distance traveled is {distance} miles")

#Boolean is a data type that can only have two values: True or False. They are used to represent the truth value of a statement or condition.
#Assigning variables for a Boolean

is_raining = True
print(f"Is it raining?:{is_raining}")